#!/usr/bin/env node
/**
 * Embed the official gift-card fonts and logo as base64 TypeScript modules.
 * The Supabase Edge bundler does not upload sibling .ttf/.png files referenced
 * only via `new URL(..., import.meta.url)`, so Deno.readFile fails at runtime.
 * Re-run this script after changing any file under
 * supabase/functions/_shared/gift-card-pdf/assets/.
 *
 *   node scripts/embed-gift-card-pdf-assets.mjs
 *   node scripts/embed-gift-card-pdf-assets.mjs --check
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const assetRoot = join(root, 'supabase/functions/_shared/gift-card-pdf');
const outFile = join(assetRoot, 'embeddedAssets.ts');

const ASSETS = [
  'assets/fonts/Montserrat-Regular.ttf',
  'assets/fonts/Montserrat-Medium.ttf',
  'assets/fonts/Montserrat-SemiBold.ttf',
  'assets/fonts/Montserrat-Italic.ttf',
  'assets/fonts/CormorantGaramond-Regular.ttf',
  'assets/logos/logo-casa-rosier.png'
];

const WRAP = 120;

const wrapBase64 = (value) => {
  const lines = [];
  for (let i = 0; i < value.length; i += WRAP) {
    lines.push(value.slice(i, i + WRAP));
  }
  return lines.map((line, index) => (index === 0 ? `'${line}'` : `    + '${line}'`)).join('\n');
};

const build = async () => {
  const entries = [];
  for (const relative of ASSETS) {
    const bytes = await readFile(join(assetRoot, relative));
    entries.push(`  '${relative}': decode(\n    ${wrapBase64(bytes.toString('base64'))}\n  )`);
  }

  return `/**
 * Generated by scripts/embed-gift-card-pdf-assets.mjs — do not edit by hand.
 * Re-run that script after changing any file under assets/.
 */

const decode = (value: string): Uint8Array => {
  const BufferCtor = (globalThis as { Buffer?: { from: (input: string, encoding: string) => Uint8Array } }).Buffer;
  if (BufferCtor) return new Uint8Array(BufferCtor.from(value, 'base64'));
  const binary = atob(value);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
};

export const embeddedAssets: Record<string, Uint8Array> = {
${entries.join(',\n')}
};

export const getEmbeddedAsset = (relative: string): Uint8Array | undefined => embeddedAssets[relative];
`;
};

const current = await build();
const check = process.argv.includes('--check');
if (check) {
  let existing = '';
  try {
    existing = await readFile(outFile, 'utf8');
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      console.error(`missing ${outFile}; run node scripts/embed-gift-card-pdf-assets.mjs`);
      process.exit(1);
    }
    throw error;
  }
  if (existing.replace(/\r\n/g, '\n') !== current.replace(/\r\n/g, '\n')) {
    console.error(`${outFile} is stale; run node scripts/embed-gift-card-pdf-assets.mjs`);
    process.exit(1);
  }
  console.log(`${outFile} is up to date`);
  process.exit(0);
}

await writeFile(outFile, current);
console.log(`wrote ${outFile}`);
